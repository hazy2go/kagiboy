def c_array(name, tiles):
    data = [b for t in tiles for b in encode(t)]
    lines = [", ".join(f"0x{b:02X}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"const uint8_t {name}[] = {{\n    " + ",\n    ".join(lines) + "\n};\n"


