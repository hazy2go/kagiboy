"""
Builds every graphic the ROM uses and writes rom/src/assets.c + assets.h.

DMG has 4 shades: 0 = lightest (paper), 1 = light grey, 2 = dark grey, 3 = ink.
Tiles are 8x8, 2 bits per pixel. Background and sprites share the 256 tiles at
0x8000 (GBDK's default LCDC), so the budget is laid out like this:

    0..95     font, ink on paper            (ASCII 32..127)
    96..154   font, grey on paper           (ASCII 32..90: captions, uppercase)
              (the boot screen reuses this range for the big logo)
    155..239  UI: frames, icons, button glyphs, bars, big digits
    240..255  QR code 2x2 blocks (drawn by the ROM itself)

Run:  python3 rom/assets/gen_assets.py   (the Makefile does this)
"""

