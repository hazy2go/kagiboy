def glyph(ch: str, font=FONT, size=(8, 8), offset=(0, 0)) -> list[list[int]]:
    im = Image.new("L", size, 0)
    ImageDraw.Draw(im).text(offset, ch, font=font, fill=255)
    return [[1 if im.getpixel((x, y)) > 127 else 0 for x in range(size[0])] for y in range(size[1])]


def encode(px: list[list[int]]) -> list[int]:
    """8x8 grid of shades (0..3) -> 16 bytes of 2bpp tile data."""
    out = []
    for row in px:
        lo = hi = 0
        for x, v in enumerate(row):
            lo |= (v & 1) << (7 - x)
            hi |= ((v >> 1) & 1) << (7 - x)
        out += [lo, hi]
    return out


def shade(mask, on, off=0):
    return [[on if v else off for v in row] for row in mask]


def art(s: str) -> list[list[int]]:
    """ASCII pixel art: '.'=0 ':'=1 '+'=2 '#'=3."""
    m = {".": 0, ":": 1, "+": 2, "#": 3}
    rows = [r for r in s.strip("\n").split("\n")]
    return [[m[c] for c in r.strip()] for r in rows]


def split(px, w_tiles, h_tiles):
    """Cut a (w*8)x(h*8) picture into tiles, row-major."""
    tiles = []
    for ty in range(h_tiles):
        for tx in range(w_tiles):
            tiles.append([row[tx * 8:(tx + 1) * 8] for row in px[ty * 8:(ty + 1) * 8]])
    return tiles


