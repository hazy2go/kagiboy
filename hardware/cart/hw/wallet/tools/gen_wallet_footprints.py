#!/usr/bin/env python3
"""Add the wallet variant's footprints to the project library radio.pretty.

NXP_HX2QFN-20-1EP_3x3mm_P0.4mm_EP1.9x1.9mm (SE050, U110): generated from NXP's package information for
SOT1969-1 (HX2QFN20, 23 May 2019, https://cache.nxp.com/docs/en/package-information/SOT1969-1.pdf), top view, mm,
origin = package centre:
  Figure 4 (I/O pads and solderable area): 20 pads 0.725 x 0.2 at 0.4 pitch, pad centres 1.538 from the centre
    line, centre pad 1.9 x 1.9.
  Figure 3 (solder mask opening): 0.825 x 0.3 per pad, 2.0 x 2.0 centre -> 0.05 mask margin, mask-defined nowhere.
  Figure 5 (stencil, 0.125 thick): I/O paste = pad size; centre pad paste = 4 squares 0.75 at +-0.475.
Pin order (SE050 data sheet Rev 3.8, Figure 4, transparent top view): 1-5 left side top to bottom, 6-10 bottom
left to right, 11-15 right side bottom to top, 16-20 top right to left; 21 = centre pad.
Cross-check: the JLC/EasyEDA footprint for C5190917 ("QFN-20_L3.0-W3.0-P0.40-TL-EP1.9") has the same pad size
(0.70 x 0.20), pitch (0.40) and centre pad (1.90).

Usage: gen_wallet_footprints.py OUT_DIR/radio.pretty
"""
import os, sys, uuid

NAME = 'NXP_HX2QFN-20-1EP_3x3mm_P0.4mm_EP1.9x1.9mm'
L, W, OFF, PITCH = 0.725, 0.2, 1.538, 0.4


def pads():
    out = []
    ys = [-0.8 + PITCH * i for i in range(5)]
    for i, y in enumerate(ys):                       # 1-5 left, top to bottom
        out.append((str(1 + i), -OFF, y, L, W))
    for i, x in enumerate(ys):                       # 6-10 bottom, left to right
        out.append((str(6 + i), x, OFF, W, L))
    for i, y in enumerate(reversed(ys)):             # 11-15 right, bottom to top
        out.append((str(11 + i), OFF, y, L, W))
    for i, x in enumerate(reversed(ys)):             # 16-20 top, right to left
        out.append((str(16 + i), x, -OFF, W, L))
    return out


def footprint():
    u = lambda: str(uuid.uuid4())
    lines = [f'(footprint "{NAME}"', '\t(version 20241229)', '\t(generator "gen_wallet_footprints")',
             '\t(layer "F.Cu")',
             '\t(descr "NXP SOT1969-1 HX2QFN20 3x3 mm 0.4 pitch, land pattern per NXP package information Figures 3-5 '
             '(SE050), generated by hw/wallet/tools/gen_wallet_footprints.py")',
             '\t(tags "HX2QFN20 SOT1969-1 SE050")', '\t(attr smd)',
             f'\t(property "Reference" "REF**" (at 0 -2.6 0) (layer "F.SilkS") (uuid "{u()}") (effects (font (size 0.8 0.8) (thickness 0.12))))',
             f'\t(property "Value" "{NAME}" (at 0 2.6 0) (layer "F.Fab") (uuid "{u()}") (effects (font (size 0.8 0.8) (thickness 0.12))))']
    for n, x, y, w, h in pads():
        lines.append(f'\t(pad "{n}" smd rect (at {x:g} {y:g}) (size {w:g} {h:g}) (layers "F.Cu" "F.Paste" "F.Mask") '
                     f'(solder_mask_margin 0.05) (uuid "{u()}"))')
    # centre pad: copper + mask only, paste as four 0.75 squares (Figure 5)
    lines.append(f'\t(pad "21" smd rect (at 0 0) (size 1.9 1.9) (layers "F.Cu" "F.Mask") (solder_mask_margin 0.05) '
                 f'(zone_connect 2) (uuid "{u()}"))')
    for x in (-0.475, 0.475):
        for y in (-0.475, 0.475):
            lines.append(f'\t(pad "" smd rect (at {x:g} {y:g}) (size 0.75 0.75) (layers "F.Paste") (uuid "{u()}"))')
    body = [(-1.5, -1.5), (1.5, -1.5), (1.5, 1.5), (-1.5, 1.5)]
    for a, b in zip(body, body[1:] + body[:1]):
        lines.append(f'\t(fp_line (start {a[0]:g} {a[1]:g}) (end {b[0]:g} {b[1]:g}) (stroke (width 0.1) (type solid)) '
                     f'(layer "F.Fab") (uuid "{u()}"))')
    # silk: corner ticks clear of the pads, pin-1 dot at top left
    s = 1.6
    for sx, sy in ((-1, -1), (1, -1), (1, 1), (-1, 1)):
        lines.append(f'\t(fp_line (start {sx * s:g} {sy * s:g}) (end {sx * 1.15:g} {sy * s:g}) (stroke (width 0.12) (type solid)) '
                     f'(layer "F.SilkS") (uuid "{u()}"))')
        lines.append(f'\t(fp_line (start {sx * s:g} {sy * s:g}) (end {sx * s:g} {sy * 1.15:g}) (stroke (width 0.12) (type solid)) '
                     f'(layer "F.SilkS") (uuid "{u()}"))')
    lines.append(f'\t(fp_circle (center -2.0 -1.35) (end -1.9 -1.35) (stroke (width 0.2) (type solid)) (fill yes) '
                 f'(layer "F.SilkS") (uuid "{u()}"))')
    c = 2.15                                         # pads reach 1.9, +0.25 courtyard
    lines.append(f'\t(fp_rect (start {-c:g} {-c:g}) (end {c:g} {c:g}) (stroke (width 0.05) (type solid)) (fill no) '
                 f'(layer "F.CrtYd") (uuid "{u()}"))')
    lines.append(')')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    out = sys.argv[1]
    path = os.path.join(out, NAME + '.kicad_mod')
    open(path, 'w').write(footprint())
    print('wrote', path)
