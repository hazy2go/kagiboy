// Writes the PIO programs the cycle simulation validated for the board as built (Croco wiring, TXB0108 data bus,
// ROM read window) to firmware/rp2350/cart/pio/, so the firmware assembles exactly what was simulated.
// usage: pnpm exec tsx ../hardware/sim/emit-pio.ts [MHz]   (from web/)
import { mkdirSync, writeFileSync } from "node:fs";
import { buildDesign } from "./programs";

const mhz = Number(process.argv[2] ?? 150);
const d = buildDesign("romWindow", "A", mhz, "croco");
const dir = new URL("../../firmware/rp2350/cart/pio/", import.meta.url);
mkdirSync(dir, { recursive: true });
for (const sm of d.sms) {
  let src = sm.src;
  for (const [name, pin] of Object.entries(sm.defs)) src = src.replace(new RegExp(`\\b${name}\\b`, "g"), String(pin));
  const notes = Object.entries(d.notes).map(([k, v]) => `;   ${k}: ${v.toFixed(1)} ns`).join("\n");
  const head = `; Generated by hardware/sim/emit-pio.ts from hardware/sim/programs.ts (${d.variant}, Rev ${d.rev}, ${d.wiring} wiring,
; ${mhz} MHz system clock). This is the program the cycle-level simulation runs; regenerate, don't edit.
; Pins are relative to the PIO block's GPIOBASE = 16: CLK 1, /RD 2, /CS 3, A0-A15 4-19, D0-D7 20-27.
; ${JSON.stringify(sm.cfg)}
${notes}
`;
  writeFileSync(new URL(`gb_${sm.name}.pio`, dir), head + src.replace(/^\n+/, "") + "\n");
  console.log(`gb_${sm.name}.pio: ${sm.prog.lines.length} instructions`);
}
