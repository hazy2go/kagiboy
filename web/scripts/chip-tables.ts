// Writes firmware/rp2350/core/src/tables.rs from the browser chip's own tables, so the cartridge firmware and the
// web chip can never disagree on networks, swap tokens, fees or the partner wallet.
// usage: pnpm exec tsx scripts/chip-tables.ts
import { writeFileSync } from "node:fs";
import { EVM_NETWORKS } from "../src/chip/networks";
import { PARTNER_FEE, SOLVER_FEE_BPS, SWAP_TOKENS, sodaxChain } from "../src/chip/tokens";

const q = (s: string) => JSON.stringify(s);
let out = `// Generated by web/scripts/chip-tables.ts from web/src/chip/{networks,tokens}.ts. Do not edit.\n\n`;
out += `/// (chain id, home-screen name, approve-screen label, coin) in the browser chip's allowlist order\n`;
out += `pub static EVM_NETWORKS: &[(u64, &str, &str, &str)] = &[\n`;
for (const n of EVM_NETWORKS) out += `    (${n.id}, ${q(n.name)}, ${q(n.label)}, ${q(n.symbol)}),\n`;
out += `];\n\n/// SODAX chain key for each EVM network the cartridge swaps on (Solana is "solana")\n`;
out += `pub static SODAX_EVM: &[(u64, &str)] = &[\n`;
for (const n of EVM_NETWORKS) {
  const k = sodaxChain({ chain: "evm", net: n.id });
  if (k) out += `    (${n.id}, ${q(k)}),\n`;
}
out += `];\n\n/// (SODAX chain, token address or mint as listed, symbol, decimals); EVM addresses are stored lower-case\n`;
out += `pub static SWAP_TOKENS: &[(&str, &str, &str, u32)] = &[\n`;
for (const [chain, list] of Object.entries(SWAP_TOKENS)) for (const [addr, t] of Object.entries(list)) out += `    (${q(chain)}, ${q(addr)}, ${q(t.symbol)}, ${t.decimals}),\n`;
out += `];\n\npub const PARTNER_FEE_BPS: u128 = ${PARTNER_FEE.bps};\npub const PARTNER_WALLET: &str = ${q(PARTNER_FEE.wallet)};\npub const SOLVER_FEE_BPS: u128 = ${SOLVER_FEE_BPS};\n`;
writeFileSync(new URL("../../firmware/rp2350/core/src/tables.rs", import.meta.url), out);
console.log(`tables.rs: ${EVM_NETWORKS.length} networks, ${Object.values(SWAP_TOKENS).reduce((n, l) => n + Object.keys(l).length, 0)} tokens`);
